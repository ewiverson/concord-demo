// demo_ui.js — the demo's only UI additions: a footer that says what this is and how to reach
// Montage Neuroscience, and an "About this demo" dialog that maps what a visitor can try to the
// services offered. Everything else in the page is the unmodified concord-server frontend.
//
// Styling follows concord-server/DESIGN.md: tokens only, sentence case, no pills, plain copy.

(function () {
    "use strict";

    // Edit these when the site changes.
    var SITE_URL = "https://www.montageneuroscience.com/";
    var DOCS_URL = "/docs/index.html";

    // ── Copy ───────────────────────────────────────────────────────────────

    var WHAT_IT_IS =
        "Concord is a framework for simulating and analyzing SEEG recordings, built and used by Montage Neuroscience " +
        "in its consulting work. This page is the real viewer running in your browser against a mock backend. " +
        "The recordings are generated by a neural mass model (Wendling, 2002). There is no patient data, " +
        "nothing you do here is uploaded, and it is not for clinical use.";

    // [what to try, what it demonstrates]
    var TRY = [
        ["Browse the dataset, read the subject detail, and download a subject",
         "Data standardization and sharing preparation: BIDS layout, participants metadata, sidecar files, and what is local versus in the cloud."],
        ["Open an ictal recording. Switch montage (Mono, Bi, CAR), apply a notch filter, zoom the traces",
         "Time-series analysis of EEG and SEEG: re-referencing, filtering, and reading seizure onset on the right channels."],
        ["Look at the spectrogram, PSD, line length, Hjorth parameters, band power and the 3D brain",
         "Spectral and signal features, and mapping them back to electrode positions."],
        ["Open the documentation",
         "Research software and reproducibility: separate tested packages, documented interfaces, and a build that publishes this page from source."],
    ];

    var NOT_SHOWN =
        "Offered but not shown here: low-noise measurement system design, statistical and simulation modeling, " +
        "and de-identification and database tooling.";

    var NEXT_STEP =
        "If you have EDF or BIDS data and a question about it, a free 30-minute scoping call is the way to start.";

    var DESKTOP_NOTICE_TITLE = "Open this on a desktop computer";
    var DESKTOP_NOTICE_BODY =
        "The Concord demo is a data viewer built for a large screen and a mouse. It does not work on phones or tablets. " +
        "Open this page in a desktop browser such as Chrome, Firefox, Safari or Edge.";

    // Treated as "not a desktop": a narrow viewport, or a device with no hover and a coarse (touch) pointer.
    var NOT_DESKTOP_QUERY = "(max-width: 899px), (hover: none) and (pointer: coarse)";

    // ── Small DOM helpers ──────────────────────────────────────────────────

    function el(tag, className, text) {
        var node = document.createElement(tag);
        if (className) node.className = className;
        if (text) node.textContent = text;
        return node;
    }

    function link(href, text, newTab) {
        var a = el("a", "demo-link", text);
        a.href = href;
        if (newTab) { a.target = "_blank"; a.rel = "noopener"; }
        return a;
    }

    // ── Styles (tokens from style.css; sizes follow the A-/A+ text scale) ──

    function addStyles() {
        var css =
            ":root { --demo-footer-h: calc(30px * var(--font-scale)); }" +
            // The views are 100vh tall; give the footer real space instead of covering them.
            "#browser-view, #analysis-view { height: calc(100vh - var(--demo-footer-h)); }" +
            "#demo-footer { flex-shrink: 0; height: var(--demo-footer-h); display: flex; align-items: center; gap: 14px;" +
            "  padding: 0 12px; background: var(--bg-panel); border-top: 1px solid var(--border);" +
            "  font-size: calc(12px * var(--font-scale)); color: var(--text-muted); white-space: nowrap; overflow: hidden; }" +
            "#demo-footer .demo-grow { flex: 1; min-width: 0; overflow: hidden; text-overflow: ellipsis; }" +
            ".demo-link { color: var(--link); text-decoration: none; background: none; border: none; padding: 0;" +
            "  font: inherit; cursor: pointer; }" +
            ".demo-link:hover { text-decoration: underline; }" +
            "#demo-about { width: 640px; max-width: calc(100vw - 32px); max-height: 82vh; }" +
            "#demo-about .demo-body { padding: 14px 18px 16px; overflow-y: auto; font-size: calc(13px * var(--font-scale));" +
            "  line-height: 1.55; color: var(--text); }" +
            "#demo-about h3 { font-size: calc(13px * var(--font-scale)); font-weight: 600; margin: 16px 0 6px; }" +
            "#demo-about h3:first-child { margin-top: 0; }" +
            "#demo-about p { margin: 0 0 6px; }" +
            "#demo-about dl { margin: 0; }" +
            "#demo-about dt { font-weight: 500; margin-top: 10px; }" +
            "#demo-about dd { margin: 2px 0 0; color: var(--text-muted); }" +
            "#demo-about .demo-actions { display: flex; align-items: center; gap: 14px; margin-top: 16px; }" +
            "#demo-about .demo-actions button.demo-primary { padding: 6px 14px; background: var(--primary); color: #fff;" +
            "  border: none; border-radius: var(--radius); cursor: pointer; font-size: calc(13px * var(--font-scale)); }" +
            "#demo-about .demo-actions button.demo-primary:hover { background: var(--primary-hover); }" +
            // Full-screen notice for phones and tablets
            "#demo-desktop-notice { position: fixed; inset: 0; z-index: 3000; background: var(--bg); display: flex;" +
            "  align-items: center; justify-content: center; padding: 24px; }" +
            "#demo-desktop-notice[hidden] { display: none; }" +
            "#demo-desktop-notice .demo-notice-body { max-width: 420px; font-size: calc(15px * var(--font-scale)); line-height: 1.55; }" +
            "#demo-desktop-notice h1 { font-size: calc(20px * var(--font-scale)); font-weight: 600; margin: 0 0 10px; }" +
            "#demo-desktop-notice p { margin: 0 0 12px; color: var(--text-secondary); }" +
            "#demo-desktop-notice .demo-notice-url { font-family: var(--font-mono); font-size: calc(13px * var(--font-scale));" +
            "  color: var(--text); word-break: break-all; }" +
            "#demo-desktop-notice .demo-actions { display: flex; flex-wrap: wrap; align-items: center; gap: 16px; margin-top: 16px; }" +
            "#demo-desktop-notice button.demo-primary { padding: 8px 16px; background: var(--primary); color: #fff; border: none;" +
            "  border-radius: var(--radius); cursor: pointer; font-size: calc(14px * var(--font-scale)); }";
        var style = el("style");
        style.textContent = css;
        document.head.appendChild(style);
    }

    // ── "About this demo" dialog ───────────────────────────────────────────

    function buildDialog() {
        var overlay = el("div", "modal-overlay");
        overlay.id = "demo-about-overlay";
        overlay.hidden = true;

        var dialog = el("div", "modal");
        dialog.id = "demo-about";
        dialog.setAttribute("role", "dialog");
        dialog.setAttribute("aria-label", "About this demo");

        var header = el("div", "modal-header");
        header.appendChild(el("span", null, "About this demo"));
        var close = el("button", "fb-close-btn", "×");
        close.setAttribute("aria-label", "Close");
        header.appendChild(close);
        dialog.appendChild(header);

        var body = el("div", "demo-body");
        body.appendChild(el("h3", null, "What this is"));
        body.appendChild(el("p", null, WHAT_IT_IS));

        body.appendChild(el("h3", null, "What to try"));
        var dl = el("dl");
        TRY.forEach(function (pair) {
            dl.appendChild(el("dt", null, pair[0]));
            dl.appendChild(el("dd", null, pair[1]));
        });
        body.appendChild(dl);

        body.appendChild(el("h3", null, "What is not in this demo"));
        body.appendChild(el("p", null, NOT_SHOWN));

        body.appendChild(el("h3", null, "Next step"));
        body.appendChild(el("p", null, NEXT_STEP));

        var actions = el("div", "demo-actions");
        var ok = el("button", "demo-primary", "Back to the demo");
        actions.appendChild(ok);
        actions.appendChild(link(SITE_URL, "Discuss your project", true));
        actions.appendChild(link(DOCS_URL, "Documentation", true));
        body.appendChild(actions);
        dialog.appendChild(body);
        overlay.appendChild(dialog);

        function open() { overlay.hidden = false; ok.focus(); }
        function hide() { overlay.hidden = true; }
        close.addEventListener("click", hide);
        ok.addEventListener("click", hide);
        overlay.addEventListener("click", function (e) { if (e.target === overlay) hide(); });
        document.addEventListener("keydown", function (e) { if (e.key === "Escape" && !overlay.hidden) hide(); });

        document.body.appendChild(overlay);
        return open;
    }

    // ── Footer ─────────────────────────────────────────────────────────────

    function buildFooter(openAbout) {
        var footer = el("div");
        footer.id = "demo-footer";

        var note = el("span", "demo-grow");
        note.appendChild(document.createTextNode("Concord is a demonstration by "));
        note.appendChild(link(SITE_URL, "Montage Neuroscience", true));
        note.appendChild(document.createTextNode(". Synthetic data, generated in your browser."));
        footer.appendChild(note);

        var about = el("button", "demo-link", "About this demo");
        about.type = "button";
        about.addEventListener("click", openAbout);
        footer.appendChild(about);
        footer.appendChild(link(SITE_URL, "Discuss your project", true));

        document.body.appendChild(footer);
    }

    // ── Desktop-only notice ────────────────────────────────────────────────

    function buildDesktopNotice() {
        var overlay = el("div");
        overlay.id = "demo-desktop-notice";
        overlay.setAttribute("role", "alert");
        overlay.hidden = true;

        var box = el("div", "demo-notice-body");
        box.appendChild(el("h1", null, DESKTOP_NOTICE_TITLE));
        box.appendChild(el("p", null, DESKTOP_NOTICE_BODY));
        box.appendChild(el("p", "demo-notice-url", location.origin + "/"));

        var actions = el("div", "demo-actions");
        var copy = el("button", "demo-primary", "Copy link");
        copy.type = "button";
        copy.addEventListener("click", function () {
            var done = function () { copy.textContent = "Link copied"; };
            if (navigator.clipboard && navigator.clipboard.writeText) {
                navigator.clipboard.writeText(location.origin + "/").then(done, function () {});
            }
        });
        actions.appendChild(copy);
        actions.appendChild(link(SITE_URL, "Montage Neuroscience", true));
        box.appendChild(actions);

        overlay.appendChild(box);
        document.body.appendChild(overlay);

        // Follow the window: a desktop window dragged narrow shows the notice, and widening it hides it again.
        var query = window.matchMedia(NOT_DESKTOP_QUERY);
        function update() { overlay.hidden = !query.matches; }
        if (query.addEventListener) query.addEventListener("change", update);
        else query.addListener(update);
        update();
    }

    document.addEventListener("DOMContentLoaded", function () {
        addStyles();
        buildFooter(buildDialog());
        buildDesktopNotice();
    });
})();
